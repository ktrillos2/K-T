import fs from 'fs'
import path from 'path'
import matter from 'gray-matter'
import { z } from 'zod'

const SourceItemSchema = z.object({
  title: z.string().min(1),
  url: z.string().url(),
})

const CtaSchema = z.object({
  badge: z.string().optional(),
  title: z.string().min(1),
  description: z.string().min(1),
  label: z.string().min(1),
  href: z.string().min(1),
}).optional()

export const MdxFrontmatterSchema = z.object({
  title: z.string().min(1),
  slug: z.string().min(1),
  description: z.string().min(1),
  excerpt: z.string().min(1),
  publishedAt: z.string().min(1),
  updatedAt: z.string().optional(),
  author: z.string().default('Keyner Trillos'),
  authorRole: z.string().default('Co-Fundador & Lead Software Engineer'),
  locale: z.string().default('es-CO'),
  draft: z.boolean().default(false),
  category: z.string().default('Ingeniería & IA'),
  primaryKeyword: z.string().optional(),
  secondaryKeywords: z.array(z.string()).default([]),
  searchIntent: z.string().optional(),
  geoTarget: z.array(z.string()).default([]),
  tags: z.array(z.string()).default([]),
  canonical: z.string().url().optional(),
  ogImageAlt: z.string().optional(),
  imagePrompt: z.string().optional(),
  sources: z.array(SourceItemSchema).default([]),
  cta: CtaSchema,
})

// 1. Read existing catalog posts from lib/blog-posts.ts to ensure ZERO duplicate slugs
const catalogContent = fs.readFileSync(path.join(process.cwd(), 'lib/blog-posts.ts'), 'utf-8')
const catalogMatches = [...catalogContent.matchAll(/slug:\s*"([^"]+)"/g)]
const catalogSlugs = new Set(catalogMatches.map((m) => m[1]))

console.log(`[Validation] Found ${catalogSlugs.size} existing catalog blog slugs in lib/blog-posts.ts`)

const dir = path.join(process.cwd(), 'content/blog')
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.mdx'))

console.log(`[Validation] Found ${files.length} MDX files in ${dir}`)

const allSlugs = new Set(catalogSlugs)
const posts = []

for (const file of files) {
  const filePath = path.join(dir, file)
  const raw = fs.readFileSync(filePath, 'utf-8')
  
  // Use mature gray-matter parser
  const parsed = matter(raw)
  const validated = MdxFrontmatterSchema.parse(parsed.data)

  // Strict Duplicate Slug Detection
  if (allSlugs.has(validated.slug)) {
    throw new Error(
      `🚨 [FATAL BUILD ERROR] Duplicate blog slug detected: "${validated.slug}" in file "${file}". A blog post with this slug already exists! Build aborted.`
    )
  }
  allSlugs.add(validated.slug)

  const words = parsed.content.trim().split(/\s+/).length
  const readTime = `${Math.ceil(words / 200)} min de lectura`

  posts.push({
    ...validated,
    content: parsed.content.trim(),
    readTime,
    filename: file,
  })
}

// Sort by publishedAt ascending (editorial schedule)
posts.sort((a, b) => new Date(a.publishedAt).getTime() - new Date(b.publishedAt).getTime())

console.log(`[Validation] Slugs verified unique across ${allSlugs.size} total articles (${catalogSlugs.size} catalog + ${posts.length} MDX).`)

const outputTs = `// Auto-generated by scripts/build-mdx-data.mjs - DO NOT EDIT DIRECTLY
export interface SourceItem {
  title: string
  url: string
}

export interface CtaConfig {
  badge?: string
  title: string
  description: string
  label: string
  href: string
}

export interface MdxPost {
  title: string
  slug: string
  description: string
  excerpt: string
  publishedAt: string
  updatedAt?: string
  author: string
  authorRole: string
  locale: string
  draft: boolean
  category: string
  primaryKeyword?: string
  secondaryKeywords: string[]
  searchIntent?: string
  geoTarget: string[]
  tags: string[]
  canonical?: string
  ogImageAlt?: string
  imagePrompt?: string
  sources: SourceItem[]
  cta?: CtaConfig
  content: string
  readTime: string
  filename: string
}

export const mdxPostsData: MdxPost[] = ${JSON.stringify(posts, null, 2)}
`

fs.writeFileSync(path.join(process.cwd(), 'lib/blog-mdx-data.ts'), outputTs, 'utf-8')
console.log(`[Build] Successfully compiled and verified ${posts.length} MDX posts to lib/blog-mdx-data.ts`)
